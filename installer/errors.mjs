// Ошибка Graph API → понятная причина, если её можно определить по коду/тексту.
export function classifyMetaError(err) {
  if (!err) return null;
  if (err.network) return 'network';
  const code = Number(err.code);
  const msg = String(err.message ?? '').toLowerCase();
  if (msg.includes('did not match the viewing app') || msg.includes('app_id in the input_token')) return 'otherApp';
  if (msg.includes('client secret') || msg.includes('appsecret') || msg.includes('access token signature')) return 'secret';
  if (code === 190 || code === 102 || code === 463 || code === 467) return 'token';
  if (code === 10 || code === 200 || (code >= 200 && code < 300)) return 'permission';
  return null;
}

